"""Generate a project from the template and run its setup and pre-commit hooks."""

import os
import subprocess
from pathlib import Path

import pytest
from copier import run_copy

TEMPLATE = Path(__file__).parents[1]

ANSWERS = {
    "package_name": "mypkg",
    "description": "A test package",
    "author_name": "Jane Doe",
    "author_email": "jane@example.com",
    "github_org_name": "janedoe",
    "prefix_channel": "janedoe/test",
}


def run(cwd: Path, *args: str, gitconfig: Path) -> str:
    # Drop the variables of the template repo's pixi environment, which would otherwise
    # override the environments selected by the generated project's tasks, and use a
    # separate global git config, which provides the author identity for commits
    env = {
        key: value
        for key, value in os.environ.items()
        if not key.startswith(("PIXI_", "CONDA_"))
    }
    env["GIT_CONFIG_GLOBAL"] = str(gitconfig)
    result = subprocess.run(
        args, cwd=cwd, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True
    )
    print(result.stdout)  # shown by pytest if the test fails
    result.check_returncode()
    return result.stdout


@pytest.mark.parametrize(
    "polars_plugin", [False, True], ids=["plain", "polars"]  # ids are used by test.yml
)
def test_template(tmp_path: Path, polars_plugin: bool) -> None:
    gitconfig = tmp_path / "gitconfig"
    gitconfig.write_text("[user]\n  name = Test\n  email = test@example.com\n")

    # vcs_ref="HEAD" includes uncommitted template changes, like `copier copy --vcs-ref=HEAD`
    project = tmp_path / "mypkg"
    run_copy(
        str(TEMPLATE),
        project,
        data={**ANSWERS, "polars_plugin": polars_plugin},
        defaults=True,
        vcs_ref="HEAD",
        quiet=True,
    )

    # Note: if direnv is installed, this also runs `direnv allow` on the temporary project
    run(project, "pixi", "run", "init", gitconfig=gitconfig)
    run(project, "pixi", "run", "pre-commit", gitconfig=gitconfig)
    # Build the conda package, like the release workflow (whose other steps need GitHub).
    # This is a slow release build, and the Polars plugin only adds dependencies, which
    # the pre-commit hooks have already built and tested, so build only without it.
    if not polars_plugin:
        run(project, "pixi", "run", "build-conda", gitconfig=gitconfig)
        assert list((project / "dist").glob("*.conda"))
    # Everything generated by the setup, hooks, and builds should be committed or ignored
    assert run(project, "git", "status", "--porcelain", gitconfig=gitconfig) == ""
